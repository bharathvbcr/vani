func TestAttack7SalaryReadsKept(t *testing.T) {
	for _, c := range attack7Kept {
		got := ParsePay(c.text)
		if len(got) != 1 || got[0].AnnualMin != c.lo || got[0].AnnualMax != c.hi {
			t.Errorf("%q = %+v, want one pay %v-%v", c.text, got, c.lo, c.hi)
		}
	}
}

func TestAttack7NotPayStaysNotPay(t *testing.T) {
	for _, s := range attack7NotPay {
		if got := ParsePay(s); len(got) != 0 {
			t.Errorf("%q read as pay: %+v", s, got)
		}
	}
}
